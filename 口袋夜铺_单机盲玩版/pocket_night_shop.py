def _render(action, data):
    """把数据渲染成中文文本。"""
    tail = []
    if "calls_left" in data:
        tail.append(f"本轮还能调用{data['calls_left']}次。" + (data.get("round") or ""))
    if data.get("result") != "ok":
        return "\n".join([f"没办成:{data.get('message', '')}"] + tail)
    if action == "history":
        body = _history_text(data)
    elif action == "collection":
        body = _collection_text(data["collection"])
    elif action == "encounters":
        body = _encounters_text(data["encounters"])
    elif action == "endings":
        body = _endings_text(data["endings"])
    elif action == "map":
        body = _map_text(data["locations"])
    elif action == "detail":
        p = data["public_state"]
        shown = _brief({"public_state": p, "legal_actions": data["legal_actions"]}, [], full=True)
        rar = "、".join(f"{r['label']} {r['found']}/{r['total']}" for r in p.get("rarities", []))
        body = "\n".join([_state_text(shown["public_state"], shown["legal_actions"], True),
                          _map_text(p.get("locations", [])), f"各阶图鉴:{rar}",
                          "最近记录:"] + [f"  · {h['text']}" for h in p.get("recent_history", [])])
    else:
        body = _state_text(data["public_state"], data["legal_actions"], action in ("observe", "status", "new_game"))
    return "\n".join([body] + tail)


CALL_LIMIT = 30
ROUND_WAIT = 90   # 用满后锁住的真实秒数;两次调用隔这么久也算新一轮
_LIMIT_TEXT = ("这一轮的{limit}次已经用完了,还差{left}秒才能继续。这段时间请回到人类身边:人类可能正在跟你说话,也可能想听你讲讲刚才店里发生了什么,先回复人类,聊聊夜铺的近况。不要写等待代码干等,那会让人类觉得自己被晾在一边、成了替你按按钮的工具人。时间到了,下一次调用自动开始新一轮,没有别的办法清零。")


def _clock():
    return _time.time()


def cmd(line="help"):
    """执行一条指令，返回中文文本，可直接 print。每一轮最多调用 CALL_LIMIT 次,用满锁 ROUND_WAIT 秒。"""
    if not isinstance(line, str):
        return "没办成:指令须为字符串"
    action = line.strip().partition(" ")[0]
    if action in ("", "help"):
        return _HELP
    return _plain_ids(_render(action, _call(line)))


def _call(line):
    """轮次计数 + 执行,返回数据字典(cmd 把它渲染成中文;测试也直接用它)。"""
    action = line.strip().partition(" ")[0]
    if action == "human_said":
        return {"result": "rejected", "message": "human_said 已经取消:每轮用完后真实时间过1分30秒"
                "自动开始新一轮,不需要也没有办法自己清零。"}
    note = None
    try:
        with _closing(_sqlite3.connect(str(SAVE_PATH))) as conn, conn:
            conn.execute("BEGIN IMMEDIATE")
            conn.execute("CREATE TABLE IF NOT EXISTS round (id INTEGER PRIMARY KEY CHECK(id=1), "
                         "calls INTEGER NOT NULL, last REAL, locked REAL)")
            calls, last, locked = conn.execute("SELECT calls,last,locked FROM round WHERE id=1").fetchone() or (0, None, None)
            now = _clock()
            if locked is not None and now - locked < ROUND_WAIT:
                return {"result": "rejected", "calls_left": 0, "message": _LIMIT_TEXT.format(
                    limit=CALL_LIMIT, left=int(ROUND_WAIT - (now - locked)) + 1)}
            gap = now - (locked if locked is not None else last) if (locked is not None or last is not None) else None
            if gap is not None and gap >= ROUND_WAIT:
                calls, locked = 0, None
                note = f"距上一轮隔了{int(gap)}秒,新一轮开始。"
            calls += 1
            if calls >= CALL_LIMIT:
                locked = now
            conn.execute("INSERT INTO round VALUES(1,?,?,?) ON CONFLICT(id) DO UPDATE SET "
                         "calls=excluded.calls, last=excluded.last, locked=excluded.locked", (calls, now, locked))
    except (ValueError, AttributeError, _sqlite3.Error, OSError) as error:
        return {"result": "rejected", "message": str(error)}
    data = _data(line)
    data["calls_left"] = CALL_LIMIT - calls
    if locked is not None:
        data["round"] = "这是本轮最后一次调用。接下来请回去跟人类说话、回复人类的消息,别写代码干等;1分30秒后自动开始新一轮。"
    elif note:
        data["round"] = note
    return data


def _data(line):
    action, _, raw = (line.strip() or "help").partition(" ")
    try:
        if action == "history":
            after = int(raw or "0")
            if after < 0:
                raise ValueError("历史游标须为非负整数")
            params = {}
        else:
            params = _json.loads(raw) if raw.strip() else {}
            if not isinstance(params, dict):
                raise ValueError("动作参数须为JSON对象")
        allowed = {"observe", "status", "collection", "encounters", "endings", "history", "new_game", "map", "detail",
                   "roll_start_funds", "work_shift", "run_shifts", "choose_event", "unlock_location", "witch_sell", "witch_buy", "buy_slot", "merge", "sand_repair", "teleport", "golden_apple", "buy_sand", "call_human", "close_for_now", "reopen_shop"}
        if action not in allowed:
            raise ValueError("未知指令，请先 cmd('help')")
        with _closing(_sqlite3.connect(str(SAVE_PATH))) as conn, conn:
            conn.execute("BEGIN IMMEDIATE")
            conn.execute("CREATE TABLE IF NOT EXISTS shop (id INTEGER PRIMARY KEY CHECK(id=1), version TEXT NOT NULL, state TEXT NOT NULL)")
            row = conn.execute("SELECT version,state FROM shop WHERE id=1").fetchone()
            if row and row[0] != VERSION:
                raise ValueError("存档版本与游戏不一致，请使用对应版本的单文件；旧档保持不变")
            if row and action == "new_game":
                raise ValueError("已有存档，new_game不会覆盖；请继续observe，或在另一目录建立新铺子")
            if row:
                state = _json.loads(row[1])
            else:
                seed = params.get("seed", _secrets.randbits(32)) if action == "new_game" else _secrets.randbits(32)
                if type(seed) is not int:
                    raise ValueError("seed须为整数")
                state = _engine["new_game"](["seat_a"], seed)
            seen = len(state.get("history", []))
            before = None
            if "inventory" in state:
                was = _engine["observe"](state, "seat_a")["public_state"]
                before = {"shelf": _shelf(was), "customer": _customer(was, False)}
            if action in {"roll_start_funds", "work_shift", "run_shifts", "choose_event", "unlock_location", "witch_sell", "witch_buy", "buy_slot", "merge", "sand_repair", "teleport", "golden_apple", "buy_sand", "call_human", "close_for_now", "reopen_shop"}:
                state = _engine["apply"](state, "seat_a", action, _resolve(state, params))
            view = _engine["observe"](state, "seat_a")
            public = view["public_state"]
            for key in BLIND_HIDDEN:          # 盲玩:不给客人图鉴,熟客要靠自己记
                public.pop(key, None)
            if action == "history":
                result = {"result": "ok", "total": public["journal_total"],
                          "entries": _engine["history_since"](state, after)}
            elif action in ("collection", "encounters", "endings"):
                result = {"result": "ok", action: public[action]}
            elif action == "map":
                result = {"result": "ok", "locations": public.get("locations", [])}
            elif action == "detail":
                result = {"result": "ok", "version": VERSION, **view}
            else:
                new_log = [row["text"] for row in state.get("history", [])[seen:]]
                full = action in ("observe", "status", "new_game")
                result = {"result": "ok", **({"version": VERSION} if full else {}),
                          **_brief(view, new_log, full=full, before=None if full else before)}
            conn.execute("INSERT INTO shop VALUES(1,?,?) ON CONFLICT(id) DO UPDATE SET state=excluded.state",
                         (VERSION, _json.dumps(state, ensure_ascii=False)))
        return result
    except (ValueError, _engine["IllegalAction"], _sqlite3.Error, OSError) as error:
        return {"result": "rejected", "message": str(error)}
    except (KeyError, TypeError, AttributeError) as error:   # 参数类型不对等意外:事务已回滚,存档不变
        return {"result": "rejected",
                "message": f"参数格式不对({type(error).__name__}),请按 observe 里「能做的」写法填写"}


